export const locales = ["en", "ar"] as const;
export type Locale = (typeof locales)[number];
export const defaultLocale: Locale = "en";
export const localeCookie = "locale";

export function isLocale(value: unknown): value is Locale {
  return locales.includes(value as Locale);
}

export function direction(locale: Locale) {
  return locale === "ar" ? "rtl" : "ltr";
}

// Western digits in both languages keep numbers consistent with SQL and raw data.
export function intlLocale(locale: Locale) {
  return locale === "ar" ? "ar-u-nu-latn" : "en-US";
}

type PluralForms = Partial<Record<Intl.LDMLPluralRule, string>> & {
  other: string;
};

function plural(locale: string, count: number, forms: PluralForms) {
  const rule = new Intl.PluralRules(locale).select(count);
  return (forms[rule] ?? forms.other).replace(
    "{n}",
    count.toLocaleString(intlLocale(locale as Locale)),
  );
}

